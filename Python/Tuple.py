my_tup = (1,2,3,4,5) # this will create a tuple with elements 1,2,3,4,5

print(my_tup) # this will print the tuple

my_tuplist = list(my_tup) # this will convert the tuple to a list

my_tuplist.append(6) # this will add the element 6 to the list

print(my_tuplist) # this will print the updated list

my_tup = tuple(my_tuplist) # this will convert the list back to a tuple

print(my_tup) # this will print the updated tuple
